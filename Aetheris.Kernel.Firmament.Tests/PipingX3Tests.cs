    [Fact]
    public void StandardPipingLibrary_ResolvesGenericProducts()
    {
        const string source="""
            Use Standard.Piping
            Model LibraryWitness {
                Units: mm
                Let Pipe = Standard.Piping.Pipe
                Let Elbow = Standard.Piping.Elbow90
                Let Tee = Standard.Piping.Tee
            }
            """;
        var resolved=FirmamentStandardLibraryResolver.Resolve(source,out var diagnostics);
        Assert.NotNull(resolved);Assert.Empty(diagnostics);
        Assert.Contains("Struct PipeTemplate",resolved.Source,StringComparison.Ordinal);
        Assert.Contains("Struct Elbow90Template",resolved.Source,StringComparison.Ordinal);
        Assert.Contains("Struct TeeTemplate",resolved.Source,StringComparison.Ordinal);
    }

    private static string FindRoot(){var d=new DirectoryInfo(AppContext.BaseDirectory);while(d is not null&&!File.Exists(Path.Combine(d.FullName,"Aetheris.slnx")))d=d.Parent;return d?.FullName??throw new DirectoryNotFoundException();}

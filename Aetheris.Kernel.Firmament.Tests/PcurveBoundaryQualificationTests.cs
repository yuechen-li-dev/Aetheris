using Aetheris.Kernel.Core.Brep;
using Aetheris.Kernel.Core.Step242;

namespace Aetheris.Kernel.Firmament.Tests;

public sealed class PcurveBoundaryQualificationTests
{
    [Theory]
    [InlineData("axis-coil.firmament")]
    [InlineData("helix.firmament")]
    public void GeneratedCoilBoundaryBoundsAlsoPassIndependentDenseLiftChecks(string name)
    {
        var path = Path.GetFullPath(Path.Combine(AppContext.BaseDirectory, "../../../../fixtures/Canonical/WireForm", name));
        var built = FirmamentBuildAndExport.CompileSource(File.ReadAllText(path), Path.GetDirectoryName(path));
        Assert.True(built.IsSuccess, string.Join("; ", built.Diagnostics));
        // This must import this execution's generated bytes, rather than a cached
        // external corpus body: it qualifies the real compiler roundtrip.
        var imported = Step242Importer.ImportBody(built.Value.StepText);
        Assert.True(imported.IsSuccess, string.Join("; ", imported.Diagnostics));
        var body = imported.Value;
        var certified = body.Bindings.PcurveBindings.Where(p => p.Qualification?.RecoveryMethod == "BezierBoundaryControlHull").ToArray();
        Assert.True(certified.Length > 100);
        Assert.All(certified, p => {
            Assert.Equal(0, p.Qualification!.LiftSamples);
            Assert.InRange(p.Qualification.MaximumLiftDeviationMillimetres, 0d, p.Qualification.QualificationToleranceMillimetres);
        });
        // An independent grid, unrelated to the old 8193-point guard, verifies
        // the actual recovered trims and complete UV-loop closure.
        var evidence = BrepPcurveValidator.Validate(body, 1e-5, requireEveryCoedge: true, samples: 4099);
        Assert.True(evidence.IsValid, string.Join("; ", evidence.Diagnostics));
    }
}

"""Small, repository-owned PDF witness: inherited CropBox, four rotations, UserUnit=2.

The red rectangle is at local (20, 20)..(60, 40) before rotation/scaling.
Generated bytes are deterministic and contain no third-party drawing content.
"""
from pathlib import Path

objects = [
    b"<< /Type /Catalog /Pages 2 0 R >>",
    b"<< /Type /Pages /Kids [3 0 R 4 0 R 5 0 R 6 0 R] /Count 4 /MediaBox [0 0 400 300] /CropBox [10 20 210 120] >>",
]
for rotation in (0, 90, 180, 270):
    objects.append(f"<< /Type /Page /Parent 2 0 R /Rotate {rotation} /UserUnit 2 /Resources << >> /Contents 7 0 R >>".encode())
stream = b"1 0 0 rg 30 40 40 20 re f\n"
objects.append(b"<< /Length " + str(len(stream)).encode() + b" >>\nstream\n" + stream + b"endstream")
pdf = bytearray(b"%PDF-1.7\n")
offsets = [0]
for i, obj in enumerate(objects, 1):
    offsets.append(len(pdf))
    pdf.extend(f"{i} 0 obj\n".encode() + obj + b"\nendobj\n")
xref = len(pdf)
pdf.extend(f"xref\n0 {len(offsets)}\n0000000000 65535 f \n".encode())
for offset in offsets[1:]:
    pdf.extend(f"{offset:010d} 00000 n \n".encode())
pdf.extend(f"trailer\n<< /Size {len(offsets)} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode())
Path(__file__).with_name("page-coordinates.pdf").write_bytes(pdf)
